/**
 * vector から 4 letter コードを生成する。
 *   shoubu  ≥ 0 → R / < 0 → E
 *   keiei   ≥ 0 → W / < 0 → H
 *   kansen  ≥ 0 → U / < 0 → A
 *   kanshin ≥ 0 → O / < 0 → F
 */
export function vectorToCode(v) {
  return (
    (v.shoubu  >= 0 ? 'R' : 'E') +
    (v.keiei   >= 0 ? 'W' : 'H') +
    (v.kansen  >= 0 ? 'U' : 'A') +
    (v.kanshin >= 0 ? 'O' : 'F')
  )
}
